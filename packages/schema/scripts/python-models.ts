// Writes python/layering/contract.py, the layer split app's Pydantic models, from the layer split's job
// contract in src/ai.ts (ADR-0002): zod's JSON Schema of each model, turned into Pydantic by
// datamodel-code-generator, run through uv in the python/ workspace. With --check it writes nothing, and
// fails when the file is not what it would write.
//   node packages/schema/scripts/python-models.ts [--check]
import { execFileSync } from 'node:child_process'
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { parseArgs } from 'node:util'

import { z } from 'zod'

import { LayerSplitRequest, LayerSplitResult } from '../src/ai.ts'

/** The Python workspace, which holds datamodel-code-generator. */
const PYTHON = fileURLToPath(new URL('../../../python/', import.meta.url))
/** The generated file. */
const CONTRACT = join(PYTHON, 'layering', 'contract.py')

/** The models the app reads and writes, by their Python names. */
const MODELS = { LayerSplitRequest, LayerSplitResult }

const { values } = parseArgs({ options: { check: { type: 'boolean', default: false } } })
const generated = pythonModels()
if (!values.check) {
  writeFileSync(CONTRACT, generated)
  console.log(`wrote ${CONTRACT}`)
} else if (readFileSync(CONTRACT, 'utf8').replace(/\r\n/g, '\n') !== generated) {
  console.error(
    'python/layering/contract.py is stale: run `pnpm --filter @dazbee/schema python-models` and commit what it writes',
  )
  process.exit(1)
} else {
  console.log('python/layering/contract.py matches packages/schema/src/ai.ts')
}

/** The Python models of `MODELS`, as datamodel-code-generator writes them. */
function pythonModels(): string {
  const registry = z.registry<{ id: string }>()
  for (const [id, model] of Object.entries(MODELS)) registry.add(model, { id })
  const { schemas } = z.toJSONSchema(registry, { target: 'draft-2020-12', uri: (id) => `#/$defs/${id}` })
  // Each model's own `$schema` goes: the file names the dialect once, at its root.
  const defs = Object.fromEntries(
    Object.entries(schemas).map(([id, schema]) => [
      id,
      Object.fromEntries(Object.entries(schema).filter(([key]) => key !== '$schema')),
    ]),
  )
  const folder = mkdtempSync(join(tmpdir(), 'python-models-'))
  try {
    const input = join(folder, 'layer-split.json')
    const output = join(folder, 'contract.py')
    // The root names either model, so the file holds the two models and no model of its own.
    const root = { anyOf: Object.keys(defs).map((id) => ({ $ref: `#/$defs/${id}` })), $defs: defs }
    writeFileSync(input, JSON.stringify({ $schema: 'https://json-schema.org/draft/2020-12/schema', ...root }))
    execFileSync(
      'uv',
      [
        'run',
        '--frozen',
        '--directory',
        PYTHON,
        'datamodel-codegen',
        '--input',
        input,
        '--input-file-type',
        'jsonschema',
        '--output',
        output,
        '--output-model-type',
        'pydantic_v2.BaseModel',
        '--target-python-version',
        '3.12',
        '--class-name',
        'LayerSplitMessage',
        '--formatters',
        'builtin',
        '--disable-timestamp',
        '--use-annotated',
        '--field-constraints',
        '--use-double-quotes',
        '--custom-file-header',
        '# Generated by packages/schema/scripts/python-models.ts from packages/schema/src/ai.ts; never edit it.',
      ],
      // Its warnings about base64, a format Pydantic has no type for, are left out.
      { stdio: ['ignore', 'ignore', 'inherit'], env: { ...process.env, PYTHONWARNINGS: 'ignore' } },
    )
    return readFileSync(output, 'utf8').replace(/\r\n/g, '\n')
  } finally {
    rmSync(folder, { recursive: true, force: true })
  }
}
